/* New language routes and bounded browser exercise: actual behavior, accessibility and safety. */
'use strict';
const fs = require('node:fs'), path = require('node:path'), http = require('node:http'), assert = require('node:assert/strict');
const { chromium } = require('playwright');
const { axeSource } = require('./qa-deps.cjs');
const root = path.resolve(process.env.SITE_EVOLUTION_DIST || path.join(__dirname, '../dist'));
const output = path.resolve(process.env.SITE_EVOLUTION_OUTPUT || path.join(__dirname, '../audit-v14.2/evolution'));
fs.mkdirSync(output, { recursive: true });
const checks = []; let browser;
const mime = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.woff2': 'font/woff2', '.svg': 'image/svg+xml', '.png': 'image/png', '.webp': 'image/webp' };
const server = http.createServer((req, res) => {
  const file = path.resolve(root, '.' + new URL(req.url, 'http://localhost').pathname);
  if (!file.startsWith(root + path.sep)) return res.writeHead(403).end();
  fs.readFile(file, (err, data) => { if (err) return res.writeHead(404).end(); res.setHeader('Content-Type', mime[path.extname(file)] || 'application/octet-stream'); res.end(data); });
});
const check = async (name, fn) => { const detail = await fn(); checks.push({ name, passed: true, ...detail }); console.log('PASS ' + name); };
const save = fatal => fs.writeFileSync(path.join(output, 'results.json'), JSON.stringify({ total: checks.length, passed: checks.filter(c => c.passed).length, browser: browser?.version(), checks, ...(fatal ? { fatal: String(fatal.stack || fatal) } : {}) }, null, 2));
(async () => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = 'http://127.0.0.1:' + server.address().port;
  browser = await chromium.launch({ ...(process.env.SITE_CHROMIUM ? { executablePath: process.env.SITE_CHROMIUM } : {}), headless: true, args: ['--no-sandbox'] });
  for (const language of ['es', 'en']) for (const theme of ['dark', 'paper', 'retro']) for (const width of [320, 1440]) await check(`exercise ${language}/${theme}/${width}`, async () => {
    const context = await browser.newContext({ viewport: { width, height: 900 }, reducedMotion: 'reduce' });
    await context.addInitScript(theme => {
      if (theme === 'paper') localStorage.setItem('iphobiuss:theme', 'paper');
      if (theme === 'retro') localStorage.setItem('iphobiuss:retro', 'on');
      window.__csp = []; document.addEventListener('securitypolicyviolation', e => window.__csp.push(e.violatedDirective));
    }, theme);
    const page = await context.newPage(), errors = [], requests = [];
    page.on('pageerror', e => errors.push(e.message)); page.on('request', r => requests.push({url:r.url(),type:r.resourceType(),method:r.method()}));
    await page.goto(base + '/' + (language === 'en' ? 'report-gen-en.html' : 'report-gen-demo.html'));
    await page.evaluate(() => document.fonts.ready);
    const exercise = page.locator('[data-finding-demo]');
    await exercise.scrollIntoViewIfNeeded();
    assert.equal(await page.locator('html').getAttribute('lang'), language);
    assert.equal(await page.locator('fieldset').isDisabled(), false);
    const requestsBefore = requests.length;
    const literal = '<img src=x onerror="window.__unsafe=1"> & <script>bad()</script>';
    await page.locator('#finding-title').fill(literal);
    await page.locator('#finding-observation').fill('Technical evidence only.');
    await page.locator('#finding-impact').fill('Business impact only.');
    await page.locator('[data-finding-form] button[type=submit]').click();
    assert.deepEqual(await page.locator('[data-finding-output="title"]').allTextContents(), [literal, literal]);
    assert.equal(await exercise.locator('img,script').count(), 0);
    assert.equal(await page.evaluate(() => window.__unsafe), undefined);
    assert.match(await page.locator('.finding-preview').nth(0).innerText(), /Technical evidence only\./);
    assert.doesNotMatch(await page.locator('.finding-preview').nth(0).innerText(), /Business impact only\./);
    assert.match(await page.locator('.finding-preview').nth(1).innerText(), /Business impact only\./);
    assert.doesNotMatch(await page.locator('.finding-preview').nth(1).innerText(), /Technical evidence only\./);
    const interactionRequests = requests.slice(requestsBefore).filter(r => r.type !== 'image');
    assert.deepEqual(interactionRequests, [], 'Editing sends no request; scroll may load an existing lazy image');
    assert.ok(requests.every(r=>r.url.startsWith(base+'/')), 'No external requests');
    await page.locator('[data-finding-form] button[type=reset]').click();
    await page.waitForFunction(() => [...document.querySelectorAll('[data-finding-output="title"]')].every(n => n.textContent === document.querySelector('#finding-title').value));
    assert.doesNotMatch(await page.locator('#finding-title').inputValue(), /<img/);
    // Native required validation prevents an empty title from silently replacing an accepted preview.
    const previous = await page.locator('[data-finding-output="title"]').first().textContent();
    await page.locator('#finding-title').fill('');
    await page.locator('[data-finding-form] button[type=submit]').click();
    assert.equal(await page.locator('[data-finding-output="title"]').first().textContent(), previous);
    await page.locator('[data-finding-form] button[type=reset]').click();
    await page.waitForFunction(() => !!document.querySelector('#finding-title').value);
    await page.evaluate(() => scrollTo(0, 0));
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.evaluate(axeSource);
    const axe = await page.evaluate(() => window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a','wcag2aa','wcag21a','wcag21aa','wcag22aa'] } }).then(r => ({ violations: r.violations.map(v => ({id:v.id,nodes:v.nodes.map(n=>n.target)})), incomplete: r.incomplete.map(v => v.id) })));
    assert.deepEqual(axe.violations, []);
    assert.deepEqual(errors, []); assert.deepEqual(await page.evaluate(() => window.__csp), []);
    const screenshot = `exercise-${language}-${theme}-${width}.png`;
    await page.evaluate(() => { document.activeElement?.blur(); scrollTo(0, 0); });
    await page.screenshot({ path: path.join(output, screenshot), fullPage: true, animations: 'disabled' });
    await context.close(); return { axe, screenshot, editingRequests: 0 };
  });
  for (const file of ['english.html','cap-case-en.html','forest-case-en.html','report-gen-en.html']) await check('English route and controls: ' + file, async () => {
    const context = await browser.newContext({ viewport: { width: 390, height: 900 } }); const page = await context.newPage();
    await page.goto(base + '/' + file); await page.evaluate(() => document.fonts.ready);
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    assert.equal(await page.locator('h1').count(), 1);
    assert.equal(await page.locator('#site-nav [aria-current=page]').getAttribute('href'), file);
    assert.equal(await page.locator('script[type="application/ld+json"]').evaluate(node => JSON.parse(node.textContent).inLanguage), 'en');
    await page.locator('[data-appearance]>summary').click();
    assert.equal(await page.locator('[data-appearance]>summary').innerText(), 'Appearance');
    await page.locator('[data-paper-toggle]').click();
    assert.match(await page.locator('[data-paper-toggle]').getAttribute('aria-label'), /^Paper ON/);
    assert.match(await page.locator('#action-status').innerText(), /^Paper enabled/);
    await page.locator('[data-retro-toggle]').click();
    assert.match(await page.locator('[data-retro-toggle]').getAttribute('aria-label'), /CRT appearance/);
    assert.match(await page.locator('#action-status').innerText(), /^Retro enabled/);
    assert.equal(await page.locator('[data-motion-toggle]').getAttribute('aria-label'), 'Background motion');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('[data-appearance]').getAttribute('open'), null);
    await page.locator('.crt-on').waitFor({state:'detached'});
    await page.evaluate(() => { document.activeElement?.blur(); scrollTo(0, 0); });
    await page.screenshot({path:path.join(output,file.replace('.html','')+'-390.png'),fullPage:true});
    await context.close(); return {englishMetadata:true,translatedControls:true};
  });
  for (const language of ['es','en']) await check('No JavaScript fallback ' + language, async () => {
    const context = await browser.newContext({ javaScriptEnabled: false, viewport: {width:320,height:900} });
    const page = await context.newPage(); await page.goto(base + '/' + (language==='en'?'report-gen-en.html':'report-gen-demo.html'));
    assert.equal(await page.locator('#finding-title').isDisabled(), true);
    assert.equal(await page.locator('.finding-preview').count(),2);
    assert.ok((await page.locator('.finding-preview').first().innerText()).length>100);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    await context.close(); return {staticComparison:true,disabledForm:true};
  });
  await check('Native specialty evidence and English entry points', async () => {
    const context = await browser.newContext({javaScriptEnabled:false,viewport:{width:320,height:900}}); const page=await context.newPage(); await page.goto(base+'/index.html');
    assert.deepEqual(await page.locator('.welcome-specialties a').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('href'))),['cap-caso.html','forest-caso.html','ia-limites.html']);
    assert.equal(await page.locator('.welcome-language').getAttribute('href'),'english.html');
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
    for(const target of ['cap-caso.html','forest-caso.html','ia-limites.html','english.html']) assert.equal((await page.request.get(base+'/'+target)).status(),200);
    await context.close();return {specialties:3,englishEntry:true};
  });
  await check('Storage denied keeps exercise usable and ephemeral', async () => {
    const context = await browser.newContext();
    await context.addInitScript(()=>{for(const name of ['getItem','setItem','removeItem'])Object.defineProperty(Storage.prototype,name,{value(){throw new DOMException('denied','SecurityError');}});});
    const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));await page.goto(base+'/report-gen-en.html');
    await page.locator('[data-site-intro][open]').waitFor({state:'hidden'});
    await page.locator('#finding-title').fill('Unsaved example');
    assert.equal(await page.locator('#finding-title').inputValue(),'Unsaved example');
    await page.locator('[data-finding-form] button[type=submit]').click();
    assert.equal(await page.locator('[data-finding-output="title"]').first().innerText(),'Unsaved example');await page.reload();
    assert.notEqual(await page.locator('#finding-title').inputValue(),'Unsaved example');assert.deepEqual(errors,[]);await context.close();return {storageRequired:false,reloadRestores:true};
  });
  save();await browser.close();await new Promise(resolve=>server.close(resolve));console.log(JSON.stringify({passed:checks.length}));
})().catch(async error=>{save(error);await browser?.close().catch(()=>{});server.close();console.error(error.stack);process.exitCode=1;});
